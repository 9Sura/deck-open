// Derive the frontend's build-time artifacts FROM the question bank.
//
// The bank itself is NOT copied and has no other home: frontend/public/question-bank/
// is the single canonical tree, written directly by the backend generators and served
// verbatim by Next.js (issue #203). What this script does is derive the two artifacts
// the app imports at BUILD time, which a `public/` file cannot satisfy:
//
//   1. lib/data/bank-manifest.json  — a copy of the bank manifest, because
//      lib/question-bank.ts `import`s it (public/ is fetched, not imported).
//   2. lib/data/pi-inventory.json   — GENERATED by scanning every bank file:
//      cluster -> level -> area -> distinct PI[]. The coverage denominator for
//      /progress (plan 08 phase 2 §5). Nothing else produces it.
//
// Node, no deps. Run via `npm run derive-bank` (or `npm run sync-data` for this plus
// vocab). `npm run sync-bank` is kept as an alias for the many plans that name it.
//
// RUN IT AFTER EVERY BANK WRITE. It is deliberately NOT a build hook: it used to run
// on `predev`/`prebuild` as part of a copy step, which re-published the bank mid-slice
// and dirtied the tree with a half-built cluster (issue #63). `npm run check-data`
// reports staleness without writing.
//
// WHAT CHANGED WITH #203: this script used to copy 20M from a backend mirror, and that
// copy was also the publish gate — the backend ran ahead while a cluster was open and
// only a sync published it. There is one tree now, so a bank write IS a publish and
// `git status` is the remaining guard. See bank_paths.py for why that was acceptable.

import { mkdir, copyFile, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "..");

// The one bank tree: canonical, generator-written, and served verbatim at
// /question-bank/... Mirrors backend/test-gen-model/src/generators/bank_paths.py.
const BANK_DIR = path.join(frontend, "public", "question-bank");
const MANIFEST_SRC = path.join(BANK_DIR, "manifest.json");
const MANIFEST_LIB_DEST = path.join(frontend, "lib", "data", "bank-manifest.json");
// The PI-coverage denominator for the /progress dashboard (plan 08 phase 2 §5).
// Frontend-only artifact — the backend manifest carries area counts but not the
// PI universe, so we derive it here by scanning the copied bank files.
const PI_INVENTORY_DEST = path.join(frontend, "lib", "data", "pi-inventory.json");
const AREA_PARAPHRASES_SRC = path.join(frontend, "lib", "data", "area-paraphrases.json");

async function main() {
  if (!existsSync(BANK_DIR)) {
    console.error(`[derive-bank] question bank not found at:\n  ${BANK_DIR}`);
    process.exit(1);
  }

  // 1. Mirror the manifest to a lib location the loader imports at build time.
  await mkdir(path.dirname(MANIFEST_LIB_DEST), { recursive: true });
  await copyFile(MANIFEST_SRC, MANIFEST_LIB_DEST);

  // 2. Report what the bank holds.
  const clusters = (await readdir(BANK_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
  let sets = 0;
  for (const c of clusters) {
    const files = (await readdir(path.join(BANK_DIR, c))).filter((f) => f.endsWith(".json"));
    sets += files.length;
  }
  console.log(`[derive-bank] read ${sets} set(s) across ${clusters.length} cluster(s): ${clusters.join(", ")}`);
  console.log(`[derive-bank]   from ${path.relative(frontend, BANK_DIR)}/`);
  console.log(`[derive-bank]   -> ${path.relative(frontend, MANIFEST_LIB_DEST)}`);

  // 3. Derive the PI inventory (the coverage denominator) by scanning every
  //    question file. cluster -> level -> area -> distinct PI[] (plan 08 phase 2
  //    §5). Level-scoped so ICDC vs District coverage is honest.
  const { inventory, piTotal, areaTotal, fileCount } = await buildPiInventory(clusters);
  await writeFile(PI_INVENTORY_DEST, serializeInventory(inventory));
  console.log(
    `[derive-bank] pi-inventory: ${piTotal} PI slot(s) across ${areaTotal} cluster×level×area group(s) from ${fileCount} file(s)`,
  );
  console.log(`[derive-bank]   -> ${path.relative(frontend, PI_INVENTORY_DEST)}`);
}

// Canonical level order so the emitted JSON is stable and reads District→ICDC.
const LEVEL_ORDER = ["District", "Association", "ICDC"];
const levelRank = (lv) => {
  const i = LEVEL_ORDER.indexOf(lv);
  return i === -1 ? LEVEL_ORDER.length : i;
};

// Sort object keys deterministically: levels by canonical rank, everything else
// alphabetically. Rebuilds the object so JSON.stringify emits a stable order.
function sortedObject(obj, keyCompare) {
  const out = {};
  for (const k of Object.keys(obj).sort(keyCompare)) out[k] = obj[k];
  return out;
}
const alpha = (a, b) => a.localeCompare(b);

export async function buildPiInventory(clusters, bankDir = BANK_DIR) {
  // cluster -> level -> area -> Set<PI>
  const acc = {};
  const bankAreas = new Set();
  let fileCount = 0;
  for (const c of clusters) {
    const dir = path.join(bankDir, c);
    const files = (await readdir(dir)).filter((f) => f.endsWith(".json"));
    for (const f of files) {
      let questions;
      try {
        questions = JSON.parse(await readFile(path.join(dir, f), "utf8"));
      } catch (err) {
        console.warn(`[derive-bank] pi-inventory: skipped unreadable ${c}/${f} (${err.message})`);
        continue;
      }
      if (!Array.isArray(questions)) continue;
      fileCount++;
      for (const q of questions) {
        const cluster = q?.cluster;
        const level = q?.level;
        const area = q?.instructionalArea;
        const pi = q?.performanceIndicator;
        if (area) bankAreas.add(area);
        if (!cluster || !level || !area || !pi) continue;
        ((acc[cluster] ??= {})[level] ??= {})[area] ??= new Set();
        acc[cluster][level][area].add(pi);
      }
    }
  }

  const areaParaphrases = JSON.parse(await readFile(AREA_PARAPHRASES_SRC, "utf8"));
  const missingParaphrases = [...bankAreas]
    .filter((area) => !areaParaphrases[area])
    .sort(alpha);
  if (missingParaphrases.length > 0) {
    throw new Error(
      `missing plain-language paraphrase(s) for instructional area(s): ${missingParaphrases.join(", ")}`,
    );
  }

  // Materialize into sorted plain objects with sorted PI arrays, and count.
  let piTotal = 0;
  let areaTotal = 0;
  const clustersOut = {};
  for (const cluster of Object.keys(acc).sort(alpha)) {
    const levelsOut = {};
    for (const level of Object.keys(acc[cluster]).sort((a, b) => levelRank(a) - levelRank(b))) {
      const areasOut = {};
      for (const area of Object.keys(acc[cluster][level]).sort(alpha)) {
        const pis = [...acc[cluster][level][area]].sort(alpha);
        areasOut[area] = pis;
        piTotal += pis.length;
        areaTotal++;
      }
      levelsOut[level] = { areas: sortedObject(areasOut, alpha) };
    }
    clustersOut[cluster] = { levels: levelsOut };
  }

  return {
    inventory: { version: 1, clusters: sortedObject(clustersOut, alpha) },
    piTotal,
    areaTotal,
    fileCount,
  };
}

// The exact bytes derive writes, so a comparison is byte-for-byte.
export const serializeInventory = (inventory) => JSON.stringify(inventory, null, 2) + "\n";

export async function clusterDirs(bankDir = BANK_DIR) {
  return (await readdir(bankDir, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
}

export { BANK_DIR, MANIFEST_SRC, MANIFEST_LIB_DEST, PI_INVENTORY_DEST };

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error("[derive-bank] failed:", err);
    process.exit(1);
  });
}
